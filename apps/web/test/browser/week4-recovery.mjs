import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.AUTH_TEST_BASE_URL;
if (!base || !process.env.RECOVERY_TASK) throw Error('Use isolated launcher');
const task = JSON.parse(process.env.RECOVERY_TASK);
const output = '/private/tmp/agent-ui-preview/output/playwright';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE });
const context = await browser.newContext({ viewport: { width: 1366, height: 768 } });
const page = await context.newPage();
page.setDefaultTimeout(30000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
    await page.goto(`${base}/?workspace=${task.workspace_id}&task=${task.external_id}`);
    await page.getByText('异常退出前已持久化的消息', { exact: true }).waitFor();
    await page.getByRole('button', { name: '展开详情', exact: true }).click();
    const panel = page.getByRole('region', { name: '会话执行占用' });
    await panel.getByRole('button', { name: '查询状态', exact: true }).click();
    await panel.getByText('查询时存在执行占用', { exact: true }).waitFor();
    const recovered = page.waitForResponse(r => r.url().endsWith('/execution/recover'));
    await panel.getByRole('button', { name: '检查并恢复异常运行', exact: true }).click();
    assert.equal((await recovered).status(), 204);
    await panel.getByText('恢复检查已完成，请刷新状态与运行历史；不会自动继续执行。', { exact: true }).waitFor();
    await panel.getByRole('button', { name: '查询状态', exact: true }).click();
    await panel.getByText('查询时未发现执行占用', { exact: true }).waitFor();
    const history = page.getByRole('region', { name: '历史运行', exact: true });
    const refreshed = page.waitForResponse(r => r.url().includes(`/tasks/${task.external_id}/runs`));
    await history.getByRole('button', { name: '刷新', exact: true }).click();
    const runs = await (await refreshed).json();
    assert.equal(runs.items[0].status, 'aborted');
    await page.getByRole('button', { name: `查看运行 ${runs.items[0].run_id}`, exact: true }).click();
    await page.getByText('原执行进程已退出，已恢复会话占用', { exact: true }).waitFor();
    await page.getByRole('button', { name: '返回列表', exact: true }).click();
    await page.screenshot({ path: `${output}/week4-recovered-1366.png` });
    console.log('PASS persistent orphan recovered through real BFF/API, message preserved');
    await page.getByLabel('你的问题').fill('恢复后继续这个任务');
    await page.getByLabel('你的问题').press('Enter');
    await page.getByText('已完成', { exact: true }).waitFor({ state: 'attached' });
    await page.reload();
    await page.getByText('恢复后继续这个任务', { exact: true }).waitFor();
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.screenshot({ path: `${output}/week4-resumed-1920.png` });
    console.log('PASS explicit new execution works and survives reload');
    for (let attempt = 0; attempt < 40; attempt++) {
        const response = await page.request.get(`${base}/api/sessions/${task.conversation_id}/execution`);
        if (!(await response.json()).occupied) break;
        await new Promise(resolve => setTimeout(resolve, 150));
    }
    await page.getByRole('button', { name: `删除任务：${task.title}`, exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: '删除任务', exact: true }).click();
    await page.getByText('任务已删除。', { exact: true }).waitFor();
    assert.equal((await page.request.get(`${base}/api/workspaces/${task.workspace_id}/tasks/${task.external_id}`)).status(), 404);
    assert.equal(new URL(page.url()).searchParams.has('task'), false);
    assert.deepEqual(errors, []);
    console.log('PASS recovered task and terminal history deleted, URL cleared');
} finally { await browser.close(); }
